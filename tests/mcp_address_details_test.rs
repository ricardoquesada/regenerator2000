    fn call_tool(
        app_state: &mut AppState,
        ui_state: &mut UIState,
        name: &str,
        args: serde_json::Value,
    ) -> serde_json::Value {
        let (tx, _rx) = oneshot::channel();
        let req = McpRequest {
            method: "tools/call".to_string(),
            params: json!({
                "name": name,
                "arguments": args
            }),
            response_sender: tx,
        };

        let response = handle_request(&req, app_state, ui_state);
        if let Some(ref err) = response.error {
            panic!("Tool {} failed with McpError: {:?}", name, err);
        }
        let result = response.result.expect("Expected result");
        let content = result["content"]
            .as_array()
            .expect("Expected CallToolResult content array");
        let text = content[0]["text"].as_str().unwrap();
        serde_json::from_str(text).unwrap_or_else(|_| json!(text))
    }

    #[test]
    fn test_block_details() {
        let mut app_state = AppState::default();
        app_state.system_config.default_is_unexplored = false;
        let origin = regenerator2000_core::state::Addr(0x1000);
        // LDA #$00 (A9 00)
        // STA $D020 (8D 20 D0)
        // JMP $1000 (4C 00 10)
        let data = vec![0xA9, 0x00, 0x8D, 0x20, 0xD0, 0x4C, 0x00, 0x10];
        app_state.load_binary(origin, data).unwrap();

        // Add some metadata
        app_state.labels.insert(
            regenerator2000_core::state::Addr(0x1000),
            vec![regenerator2000_core::state::Label {
                name: "start".to_string(),
                kind: regenerator2000_core::state::LabelKind::User,
                label_type: regenerator2000_core::state::LabelType::UserDefined,
            }],
        );
        app_state
            .annotations
            .update(regenerator2000_core::state::Addr(0x1000), |e| {
                e.user_side_comment = Some("Start of loop".to_string())
            });

        let mut ui_state = UIState::new(Theme::default());

        // Test 1: Code block at $1002 (STA $D020)
        let details = call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_get_address_details",
            json!({ "address": 0x1002 }),
        );
        println!(
            "Details 1002: {}",
            serde_json::to_string_pretty(&details).unwrap()
        );

        assert_eq!(details["address"], 0x1002);
        assert_eq!(details["type"], "Code");
        assert_eq!(details["instruction"]["mnemonic"], "STA");
        assert_eq!(details["metadata"]["referenced_address"], 0xD020);

        // Test 2: Code block at $1005 (JMP $1000)
        let details = call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_get_address_details",
            json!({ "address": 0x1005 }),
        );
        println!(
            "Details 1005: {}",
            serde_json::to_string_pretty(&details).unwrap()
        );

        assert_eq!(details["address"], 0x1005);
        assert_eq!(details["instruction"]["mnemonic"], "JMP");
        assert_eq!(details["metadata"]["target_address"], 0x1000);

        // Test 3: Metadata at $1000
        let details = call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_get_address_details",
            json!({ "address": 0x1000 }),
        );
        println!(
            "Details 1000: {}",
            serde_json::to_string_pretty(&details).unwrap()
        );

        assert_eq!(details["address"], 0x1000);
        assert_eq!(details["instruction"]["mnemonic"], "LDA");

        let labels = details["metadata"]["labels"].as_array().unwrap();
        assert!(labels.iter().any(|v| v.as_str() == Some("start")));

        let comments = details["metadata"]["comments"].as_array().unwrap();
        assert!(
            comments
                .iter()
                .any(|v| v.as_str().unwrap().contains("Start of loop"))
        );

        // Check Incoming Refs (JMP $1000 should create a ref to $1000)
        // Wait, cross_refs are generated by analyzer or disassembler?
        // In load_binary, we called disassemble() but maybe not full analysis unless auto_analyse is on?
        // AppState::load_binary calls disassemble() twice and perform_analysis() if config.auto_analyze.
        // Default config might not have auto_analyze?
        // Let's force analysis or just check if it was generated.
        // references are usually generated during analysis phase.

        // Let's manually trigger analysis if needed, but AppState::default() might not have it.
        // Actually, let's just assert that if refs are present, they are correct.
        if let Some(refs) = details["metadata"]["cross_refs_in"].as_array() {
            assert!(refs.iter().any(|v| v.as_u64() == Some(0x1005)));
            let typed_refs = details["metadata"]["typed_cross_refs_in"]
                .as_array()
                .expect("typed_cross_refs_in should exist when cross_refs_in exists");
            assert!(typed_refs.iter().any(|r| {
                r["from_address"].as_u64() == Some(0x1005)
                    && r["kind"].as_str() == Some("jump")
                    && r["badge"].as_str() == Some("[J]")
            }));
        } else {
            println!("No cross refs generated (expected if analysis didn't run)");
            // Force analysis to verification
            app_state.perform_analysis();
            let details_after = call_tool(
                &mut app_state,
                &mut ui_state,
                "r2000_get_address_details",
                json!({ "address": 0x1000 }),
            );
            let refs = details_after["metadata"]["cross_refs_in"]
                .as_array()
                .expect("Cross refs should exist after analysis");
            assert!(refs.iter().any(|v| v.as_u64() == Some(0x1005)));
            let typed_refs = details_after["metadata"]["typed_cross_refs_in"]
                .as_array()
                .expect("typed_cross_refs_in should exist after analysis");
            assert!(typed_refs.iter().any(|r| {
                r["from_address"].as_u64() == Some(0x1005)
                    && r["kind"].as_str() == Some("jump")
                    && r["badge"].as_str() == Some("[J]")
            }));
        }
    }

    #[test]
    fn test_address_details_full_64k() {
        let mut app_state = AppState::default();
        app_state.system_config.default_is_unexplored = false;
        let origin = regenerator2000_core::state::Addr(0x0000);
        let mut data = vec![0u8; 65536];
        // At $0810 (2064):
        // LDA #$1B (A9 1B)
        // STA $D011 (8D 11 D0)
        // LDA #$00 (A9 00)
        // STA $D020 (8D 20 D0)
        // JSR $FFD2 (20 D2 FF)
        // RTS (60)
        data[0x0810..0x081E].copy_from_slice(&[
            0xA9, 0x1B, 0x8D, 0x11, 0xD0, 0xA9, 0x00, 0x8D, 0x20, 0xD0, 0x20, 0xD2, 0xFF, 0x60,
        ]);
        app_state.load_binary(origin, data).unwrap();

        let mut ui_state = UIState::new(Theme::default());

        let details = call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_get_address_details",
            json!({ "address": 2064 }),
        );

        assert_eq!(details["address"], 2064);
        assert_eq!(details["type"], "Code");
        assert_eq!(details["instruction"]["mnemonic"], "LDA");

        // First address ($0000) and last address ($FFFF) should also be valid details
        let details_first = call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_get_address_details",
            json!({ "address": 0 }),
        );
        assert_eq!(details_first["address"], 0);

        let details_last = call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_get_address_details",
            json!({ "address": 0xFFFF }),
        );
        assert_eq!(details_last["address"], 0xFFFF);
    }

    #[test]
    fn test_address_details_symbolic_offset_roundtrip() {
        let mut app_state = AppState::new();
        app_state.system_config.default_is_unexplored = false;
        let origin = regenerator2000_core::state::Addr(0x1000);
        // $1000: STA $FC       (85 FC)
        // $1002: LDA $1FFF,X   (BD FF 1F)
        // $1005: RTS           (60)
        let data = vec![0x85, 0xFC, 0xBD, 0xFF, 0x1F, 0x60];
        app_state.load_binary(origin, data).unwrap();

        let mut ui_state = UIState::new(Theme::default());

        call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_set_label_name",
            json!({ "address": 0x00FB, "name": "zp_ptr" }),
        );
        call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_set_label_name",
            json!({ "address": 0x2000, "name": "table_2000" }),
        );

        // Set Tier 2 `address_offset` on external `$00FC` (`zp_ptr + 1`) and Tier 1 `operand_offset`
        // on `$1002` (`table_2000 - 1`).
        call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_set_symbolic_offset",
            json!({ "address": 0x00FC, "base": "zp_ptr" }),
        );
        call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_set_symbolic_offset",
            json!({ "address": 0x1002, "offset": -1 }),
        );

        let ext_details = call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_get_address_details",
            json!({ "address": 0x00FC }),
        );
        assert_eq!(ext_details["address"], 0x00FC);
        assert_eq!(
            ext_details["metadata"]["symbolic_offset"],
            json!({
                "expression": "zp_ptr + 1",
                "base_address": 251,
                "base_hex": "$00FB",
                "offset": 1,
                "radix": "decimal",
                "scope": "address"
            })
        );

        let tier1_details = call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_get_address_details",
            json!({ "address": 0x1002 }),
        );
        assert_eq!(tier1_details["instruction"]["operands"], "table_2000 - 1,x");
        assert_eq!(
            tier1_details["metadata"]["symbolic_offset"],
            json!({
                "expression": "table_2000 - 1",
                "base_address": 0x2000,
                "base_hex": "$2000",
                "offset": -1,
                "radix": "decimal",
                "scope": "operand"
            })
        );

        let derived_symbols = call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_get_symbols",
            json!({ "kind": "derived" }),
        );
        assert_eq!(
            derived_symbols,
            json!([
                {
                    "address": 252,
                    "name": "zp_ptr + 1",
                    "kind": "Derived",
                    "type": "SymbolicOffset",
                    "base_address": 251,
                    "offset": 1
                }
            ])
        );
    }

    #[test]
    fn test_unreferenced_system_label_derived_symbols_and_address_details() {
        use regenerator2000_core::state::{Addr, BlockType};

        let mut app_state = AppState::new();
        let mut ui_state = UIState::new(Theme::default());
        app_state.origin = Addr(0x1000);
        app_state.raw_data = vec![0x60]; // RTS only -> zero XRefs to $FFD2 / $FFD3
        app_state.block_types = vec![BlockType::Code];
        app_state.load_system_assets();
        let _ = app_state.perform_analysis();

        assert!(!app_state.labels.contains_key(&Addr(0xFFD2)));

        call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_set_symbolic_offset",
            json!({ "address": 0xFFD3, "base": "KERNAL_CHROUT", "scope": "address" }),
        );

        let details = call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_get_address_details",
            json!({ "address": 0xFFD3 }),
        );
        assert_eq!(
            details["metadata"]["symbolic_offset"]["expression"],
            "KERNAL_CHROUT + 1"
        );

        let derived = call_tool(
            &mut app_state,
            &mut ui_state,
            "r2000_get_symbols",
            json!({ "kind": "derived", "name": "KERNAL_CHROUT" }),
        );
        assert_eq!(
            derived,
            json!([
                {
                    "address": 0xFFD3,
                    "name": "KERNAL_CHROUT + 1",
                    "kind": "Derived",
                    "type": "SymbolicOffset",
                    "base_address": 0xFFD2,
                    "offset": 1
                }
            ])
        );
    }

    #[test]
    fn test_zero_page_instruction_ignores_out_of_bounds_base_across_mcp_and_navigation() {
        use regenerator2000_core::Core;
        use regenerator2000_core::state::actions::AppAction;
        use regenerator2000_core::state::{
            Addr, BlockType, Label, LabelKind, LabelType, OffsetRadix, SymbolicOffset,
        };

        let mut core = Core::new();
        core.state.origin = Addr(0x1000);
        core.state.settings.all_labels = true;
        core.state.settings.preserve_long_bytes = true;
        // $1000: B5 FF (LDA $FF,X — 2-byte ZeroPageX), $1002: BD FF 00 (LDA $00FF,X — 3-byte AbsoluteX), $1005: 60 (RTS)
        core.state.raw_data = vec![0xB5, 0xFF, 0xBD, 0xFF, 0x00, 0x60];
        core.state.block_types = vec![BlockType::Code; 6];
        core.state.labels.insert(
            Addr(0x0100),
            vec![Label {
                name: "table_0100".to_string(),
                kind: LabelKind::User,
                label_type: LabelType::Field,
            }],
        );
        core.state.annotations.update(Addr(0x0100), |e| {
            e.user_side_comment = Some("Page 1 table".to_string());
        });
        let page1_minus_1 = SymbolicOffset {
            base: Addr(0x0100),
            offset: -1,
            radix: OffsetRadix::Decimal,
        };
        // Attach the same `base = $0100` Tier 1 `operand_offset` to both sites (for example,
        // from a stale edit or corrupted project): 2-byte ZP `$1000` must reject `base > $00FF`,
        // while 3-byte AbsoluteX `$1002` honors it across comments, navigation, and MCP details.
        core.state.annotations.update(Addr(0x1000), |e| {
            e.operand_offset = Some(page1_minus_1);
        });
        core.state.annotations.update(Addr(0x1002), |e| {
            e.operand_offset = Some(page1_minus_1);
        });
        let _ = core.state.perform_analysis();
        core.state.disassemble();

        // 1. 2-byte ZP line `$1000` must NOT inherit `$0100`'s side comment or jump to `$0100`.
        let zp_idx = core
            .state
            .disassembly
            .iter()
            .position(|l| l.address == Addr(0x1000) && !l.bytes.is_empty())
            .unwrap();
        assert!(
            !core.state.disassembly[zp_idx]
                .comment
                .contains("Page 1 table")
        );

        core.view.cursor_index = zp_idx;
        core.apply_action(AppAction::JumpToOperand);
        assert_eq!(
            core.state.disassembly[core.view.cursor_index].external_label_address,
            Some(Addr(0x00FF))
        );

        // 3-byte AbsoluteX line `$1002` DOES inherit `$0100`'s side comment and jump to `$0100`.
        let abs_idx = core
            .state
            .disassembly
            .iter()
            .position(|l| l.address == Addr(0x1002) && !l.bytes.is_empty())
            .unwrap();
        assert!(
            core.state.disassembly[abs_idx]
                .comment
                .contains("Page 1 table")
        );
        core.view.cursor_index = abs_idx;
        core.apply_action(AppAction::JumpToOperand);
        assert_eq!(
            core.state.disassembly[core.view.cursor_index].external_label_address,
            Some(Addr(0x0100))
        );

        // 2. `r2000_get_address_details` on `$1000` must NOT expose `table_0100 - 1`, whereas 3-byte `$1002` DOES.
        let mut ui_state = UIState::new(Theme::default());
        let zp_details = call_tool(
            &mut core.state,
            &mut ui_state,
            "r2000_get_address_details",
            json!({ "address": 0x1000 }),
        );
        assert!(zp_details["metadata"]["symbolic_offset"].is_null());

        let abs_details = call_tool(
            &mut core.state,
            &mut ui_state,
            "r2000_get_address_details",
            json!({ "address": 0x1002 }),
        );
        assert_eq!(
            abs_details["metadata"]["symbolic_offset"]["expression"],
            "table_0100 - 1"
        );
    }
