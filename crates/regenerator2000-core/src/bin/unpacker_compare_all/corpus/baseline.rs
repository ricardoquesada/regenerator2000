//! The committed baseline: every observable R2000 output per corpus case.
//!
//! It is the zero-diff freeze for refactors and the before/after record for
//! intentional changes. The packer column keeps the **display name**
//! (Orchestrator ruling), so later API changes do not touch the file.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt;
use std::path::Path;

use serde::{Deserialize, Serialize};

use super::values::{Fnv64, HexAddr};
use super::{CaseResult, CorpusError};

/// Header written at the top of the baseline.
const BASELINE_HEADER: &str = "\
# Unpacker baseline: every observable R2000 output per corpus case.
# Generated by `UPDATE_UNPACK_BASELINE=1 cargo test -p regenerator2000-core --test unpack_corpus`.
# Do not edit by hand. Review changes with `git diff`.

";

/// Display form of a missing packer name in diffs.
const NO_PACKER: &str = "(none)";

// =============================================================================
// Rows
// =============================================================================

/// Every observable output of one successful unpack.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BaselineUnpacked {
    /// First unpacked address.
    pub start: HexAddr,
    /// Last unpacked address (inclusive).
    pub end: HexAddr,
    /// Entry point.
    pub entry: HexAddr,
    /// Depacker address.
    pub dep: HexAddr,
    /// Display name of the detected packer.
    pub packer: Option<String>,
    /// Instructions executed.
    pub instructions: u64,
    /// Payload length.
    pub len: usize,
    /// FNV-1a-64 of the payload.
    pub fnv64: Fnv64,
}

impl BaselineUnpacked {
    /// Every value with its field tag, in report order, in display form.
    fn tagged_values(&self) -> [(BaselineField, String); 8] {
        [
            (BaselineField::Start, self.start.to_string()),
            (BaselineField::End, self.end.to_string()),
            (BaselineField::Entry, self.entry.to_string()),
            (BaselineField::Dep, self.dep.to_string()),
            (
                BaselineField::Packer,
                self.packer.clone().unwrap_or_else(|| NO_PACKER.to_string()),
            ),
            (BaselineField::Instructions, self.instructions.to_string()),
            (BaselineField::Len, self.len.to_string()),
            (BaselineField::Fnv64, self.fnv64.to_string()),
        ]
    }
}

/// The observable outcome of one case.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum BaselineOutcome {
    /// The unpack succeeded.
    Unpacked(BaselineUnpacked),
    /// The unpack failed with this `UnpackError` variant.
    Failed {
        /// The variant name.
        error: String,
    },
}

impl fmt::Display for BaselineOutcome {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Unpacked(_) => f.write_str("unpacked"),
            Self::Failed { error } => write!(f, "error {error}"),
        }
    }
}

/// One baseline row (`[[row]]`).
///
/// # Example
///
/// ```toml
/// [[row]]
/// file = "c64_mule.exo3.prg"
/// start = "$0800"
/// end = "$9D19"
/// entry = "$1100"
/// dep = "$0100"
/// packer = "Exomizer 3.x"
/// instructions = 1234567
/// len = 38170
/// fnv64 = "0123456789abcdef"
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(try_from = "RawBaselineRow", into = "RawBaselineRow")]
pub struct BaselineRow {
    /// The case's fixture file name.
    pub file: String,
    /// What R2000 produced.
    pub outcome: BaselineOutcome,
}

impl BaselineRow {
    /// Captures every observable output of `result`.
    #[must_use]
    pub fn from_result(result: &CaseResult) -> Self {
        let outcome = match &result.outcome {
            Ok(image) => BaselineOutcome::Unpacked(BaselineUnpacked {
                start: HexAddr(image.start),
                end: HexAddr(image.end),
                entry: HexAddr(image.entry),
                dep: HexAddr(image.dep),
                packer: image.packer.clone(),
                instructions: image.instructions,
                len: image.data.len(),
                fnv64: image.fnv64(),
            }),
            Err(error) => BaselineOutcome::Failed {
                error: error.variant.clone(),
            },
        };
        Self {
            file: result.file.clone(),
            outcome,
        }
    }
}

/// Flat TOML shape of [`BaselineRow`], used only for (de)serialization.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct RawBaselineRow {
    file: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    start: Option<HexAddr>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    end: Option<HexAddr>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    entry: Option<HexAddr>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    dep: Option<HexAddr>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    packer: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    instructions: Option<u64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    len: Option<usize>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    fnv64: Option<Fnv64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    error: Option<String>,
}

impl TryFrom<RawBaselineRow> for BaselineRow {
    type Error = String;

    fn try_from(raw: RawBaselineRow) -> Result<Self, Self::Error> {
        let file = raw.file;
        if let Some(error) = raw.error {
            let has_result = raw.start.is_some()
                || raw.end.is_some()
                || raw.entry.is_some()
                || raw.dep.is_some()
                || raw.packer.is_some()
                || raw.instructions.is_some()
                || raw.len.is_some()
                || raw.fnv64.is_some();
            if has_result {
                return Err(format!(
                    "baseline row `{file}`: `error` cannot be combined with result keys"
                ));
            }
            return Ok(Self {
                file,
                outcome: BaselineOutcome::Failed { error },
            });
        }
        let missing = |key: &str| format!("baseline row `{file}` is missing `{key}`");
        let unpacked = BaselineUnpacked {
            start: raw.start.ok_or_else(|| missing("start"))?,
            end: raw.end.ok_or_else(|| missing("end"))?,
            entry: raw.entry.ok_or_else(|| missing("entry"))?,
            dep: raw.dep.ok_or_else(|| missing("dep"))?,
            packer: raw.packer,
            instructions: raw.instructions.ok_or_else(|| missing("instructions"))?,
            len: raw.len.ok_or_else(|| missing("len"))?,
            fnv64: raw.fnv64.ok_or_else(|| missing("fnv64"))?,
        };
        Ok(Self {
            file,
            outcome: BaselineOutcome::Unpacked(unpacked),
        })
    }
}

impl From<BaselineRow> for RawBaselineRow {
    fn from(row: BaselineRow) -> Self {
        match row.outcome {
            BaselineOutcome::Unpacked(unpacked) => Self {
                file: row.file,
                start: Some(unpacked.start),
                end: Some(unpacked.end),
                entry: Some(unpacked.entry),
                dep: Some(unpacked.dep),
                packer: unpacked.packer,
                instructions: Some(unpacked.instructions),
                len: Some(unpacked.len),
                fnv64: Some(unpacked.fnv64),
                error: None,
            },
            BaselineOutcome::Failed { error } => Self {
                file: row.file,
                start: None,
                end: None,
                entry: None,
                dep: None,
                packer: None,
                instructions: None,
                len: None,
                fnv64: None,
                error: Some(error),
            },
        }
    }
}

