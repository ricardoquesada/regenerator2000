/// A baseline value that can change between runs.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum BaselineField {
    /// First unpacked address.
    Start,
    /// Last unpacked address.
    End,
    /// Entry point.
    Entry,
    /// Depacker address.
    Dep,
    /// Packer display name.
    Packer,
    /// Instructions executed.
    Instructions,
    /// Payload length.
    Len,
    /// Payload hash.
    Fnv64,
    /// The `UnpackError` variant.
    Error,
    /// Success versus failure.
    Outcome,
}

impl fmt::Display for BaselineField {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::Start => "start",
            Self::End => "end",
            Self::Entry => "entry",
            Self::Dep => "dep",
            Self::Packer => "packer",
            Self::Instructions => "instructions",
            Self::Len => "len",
            Self::Fnv64 => "fnv64",
            Self::Error => "error",
            Self::Outcome => "outcome",
        })
    }
}

/// One difference between the committed baseline and the current run.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub enum BaselineDiff {
    /// The committed baseline has a row the current run did not produce.
    MissingRow {
        /// The case.
        file: String,
    },
    /// The current run produced a row the committed baseline lacks.
    ExtraRow {
        /// The case.
        file: String,
    },
    /// A value changed.
    Changed {
        /// The case.
        file: String,
        /// The value.
        field: BaselineField,
        /// The committed value.
        expected: String,
        /// The current value.
        actual: String,
    },
}

impl fmt::Display for BaselineDiff {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::MissingRow { file } => {
                write!(f, "{file}: in the baseline but not produced by this run")
            }
            Self::ExtraRow { file } => write!(
                f,
                "{file}: produced by this run but missing from the baseline"
            ),
            Self::Changed {
                file,
                field,
                expected,
                actual,
            } => write!(f, "{file}: {field} changed from {expected} to {actual}"),
        }
    }
}

