/// The committed snapshot of every observable output per case.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Baseline {
    /// The rows (`[[row]]`).
    #[serde(rename = "row", default, skip_serializing_if = "Vec::is_empty")]
    pub rows: Vec<BaselineRow>,
}

impl Baseline {
    /// Builds a baseline from results.
    #[must_use]
    pub fn from_results(results: &[CaseResult]) -> Self {
        Self {
            rows: results.iter().map(BaselineRow::from_result).collect(),
        }
    }

    /// Parses a baseline from TOML text.
    ///
    /// # Errors
    ///
    /// Returns [`CorpusError::Parse`] for invalid TOML, unknown keys, or a
    /// row that mixes `error` with result keys or misses a result key.
    pub fn parse(toml_text: &str) -> Result<Self, CorpusError> {
        toml::from_str(toml_text).map_err(|e| CorpusError::Parse {
            message: e.to_string(),
        })
    }

    /// Reads and parses the baseline at `path`.
    ///
    /// # Errors
    ///
    /// Returns [`CorpusError::Io`] if the file cannot be read, or any error of
    /// [`Baseline::parse`].
    pub fn load(path: &Path) -> Result<Self, CorpusError> {
        let text = std::fs::read_to_string(path).map_err(|e| CorpusError::Io {
            path: path.to_path_buf(),
            message: e.to_string(),
        })?;
        Self::parse(&text)
    }

    /// Writes the baseline in canonical form (rows sorted by file).
    ///
    /// # Errors
    ///
    /// Returns [`CorpusError::Serialize`] if TOML serialization fails.
    pub fn to_toml_string(&self) -> Result<String, CorpusError> {
        let mut canonical = self.clone();
        canonical.rows.sort_by(|a, b| a.file.cmp(&b.file));
        let body = toml::to_string(&canonical).map_err(|e| CorpusError::Serialize {
            message: e.to_string(),
        })?;
        Ok(format!("{BASELINE_HEADER}{body}"))
    }

    /// Returns a copy that keeps only the rows of `files` (used when a case
    /// filter is active, so unselected rows do not count as missing).
    #[must_use]
    pub fn restricted_to(&self, files: &BTreeSet<&str>) -> Self {
        Self {
            rows: self
                .rows
                .iter()
                .filter(|row| files.contains(row.file.as_str()))
                .cloned()
                .collect(),
        }
    }

    /// Compares the committed baseline (`self`) with the current run and
    /// returns every difference, sorted.
    #[must_use]
    pub fn compare(&self, actual: &Self) -> Vec<BaselineDiff> {
        let expected = outcomes_by_file(self);
        let current = outcomes_by_file(actual);

        let mut diffs = Vec::new();
        for (file, expected_outcome) in &expected {
            match current.get(file) {
                None => diffs.push(BaselineDiff::MissingRow {
                    file: (*file).to_string(),
                }),
                Some(current_outcome) => {
                    diffs.extend(outcome_diffs(file, expected_outcome, current_outcome));
                }
            }
        }
        diffs.extend(
            current
                .keys()
                .filter(|file| !expected.contains_key(*file))
                .map(|file| BaselineDiff::ExtraRow {
                    file: (*file).to_string(),
                }),
        );
        diffs.sort();
        diffs
    }
}

/// Indexes a baseline's outcomes by file.
fn outcomes_by_file(baseline: &Baseline) -> BTreeMap<&str, &BaselineOutcome> {
    baseline
        .rows
        .iter()
        .map(|row| (row.file.as_str(), &row.outcome))
        .collect()
}

/// Lists the changed values between two outcomes of the same case.
fn outcome_diffs(
    file: &str,
    expected: &BaselineOutcome,
    actual: &BaselineOutcome,
) -> Vec<BaselineDiff> {
    let changed = |field: BaselineField, expected: String, actual: String| {
        (expected != actual).then(|| BaselineDiff::Changed {
            file: file.to_string(),
            field,
            expected,
            actual,
        })
    };

    match (expected, actual) {
        (BaselineOutcome::Unpacked(e), BaselineOutcome::Unpacked(a)) => e
            .tagged_values()
            .into_iter()
            .zip(a.tagged_values())
            .filter_map(|((field, expected), (_, actual))| changed(field, expected, actual))
            .collect(),
        (BaselineOutcome::Failed { error: e }, BaselineOutcome::Failed { error: a }) => {
            changed(BaselineField::Error, e.clone(), a.clone())
                .into_iter()
                .collect()
        }
        _ => changed(
            BaselineField::Outcome,
            expected.to_string(),
            actual.to_string(),
        )
        .into_iter()
        .collect(),
    }
}
