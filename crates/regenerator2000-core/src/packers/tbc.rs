/// Resolves TBC Multicompactor normal (`$084A == $81`) and Firelord (`$084A == $7B`) variants,
/// reducing the segment end-address table at `$08EB` (`T3.2.6`).
#[must_use]
fn resolve_tbc(image: &LoadedImage<'_>, _sig_match: &SignatureMatch) -> Option<ResolvedSpec> {
    let mem = image.mem;
    if mem.len() < 0x08F0 {
        return None;
    }

    let is_normal = mem.get(0x084A) == Some(&0x81);
    let is_firelord = mem.get(0x084A) == Some(&0x7B);

    let valid_variant = (is_normal
        && mem.len() >= 0x08B4
        && mem.get(0x0820..0x0824) == Some(&[0xA2, 0xE9, 0xBD, 0x32]))
        || (is_firelord
            && mem.len() >= 0x08AE
            && mem.get(0x081D..0x0821) == Some(&[0xA2, 0xE9, 0xBD, 0x32]));
    if !valid_variant {
        return None;
    }

    let ret_ptr = if is_normal { 0x08B2 } else { 0x08AC };
    let entry_point = image.read_u16_le(ret_ptr)?;

    let p = 0x08EB;
    let start_addr = image.read_u16_le(p + 1)?;

    let tbl_len = usize::from(mem[p]);
    let mut q = p + tbl_len;
    let mut max_end: u32 = 0;
    while q > p && q + 1 < mem.len() {
        let strtmp = u32::from(u16::from_le_bytes([mem[q - 1], mem[q]]));
        let val = if strtmp == 0 { 0x1_0000 } else { strtmp };
        if val > max_end {
            max_end = val;
        }
        if q < 4 {
            break;
        }
        q -= 4;
    }

    let end_addr = if max_end > 0 {
        Some(AddrSource::Const((max_end as u16).wrapping_sub(1)))
    } else {
        None
    };

    Some(ResolvedSpec::from_hints(Hints {
        dep_addr: Some(AddrSource::Const(0x0100)),
        start_addr: Some(AddrSource::Const(start_addr)),
        end_addr,
        entry_point: Some(AddrSource::Const(entry_point)),
        ..Hints::NONE
    }))
}

